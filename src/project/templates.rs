//! Original minimal recipes. No downloaded wrappers, binaries, SDKs or model weights.
use super::*;
pub fn starter(args: &StarterArgs) -> io::Result<Blueprint> {
    if !valid_name(&args.name) || args.task.len() > 16384 {
        return Err(err(
            "Имя: ASCII slug a-z/0-9/-/_, до 64 символов. Задание до 16 KiB.",
        ));
    }
    if !args.profile.starter() {
        return Err(err(
            "Для этого стека используй AI blueprint; готового каркаса нет.",
        ));
    }
    profile::version_text(&args.target_version)?;
    let mut plan=Blueprint{schema_version:1,name:args.name.clone(),profile:args.profile,target_version:args.target_version.clone(),summary:format!("Minimal {} starter; the requested feature is not implemented yet.",args.profile.label()),requirements:if args.task.is_empty(){vec![]}else{vec![if args.task.len()<=2048 {args.task.clone()}else{"Full requested task is recorded in README.md".into()}]},assumptions:vec!["This is a starter, not an AI implementation of the task. Build and runtime tests have not been run by Lyra.".into()],questions:Vec::new(),files:Vec::new(),required_files:Vec::new(),provided_sources:Vec::new()};
    let mut add = |path: &str, content: String| {
        plan.files.push(PlannedFile {
            path: path.into(),
            content,
        })
    };
    let checks = args.profile.checks().join("\n");
    add(
        "README.md",
        format!(
            "# {}\n\nMinimal {} starter generated by Lyra.\n\n## Requested task\n\n{}\n\n## Manual acceptance\n\n{}\n\nCompilation/runtime tests have NOT been executed by Lyra. Review source and dependencies before running commands.\n",
            args.name,
            args.profile.label(),
            args.task,
            checks
        ),
    );
    add(
        "AGENTS.md",
        format!(
            "# Project workflow\n\n{}\n\nTarget version: {}.\nRespect user changes. Read matching official documentation before changing APIs.\nDo not claim tests passed without actual command output.\n",
            args.profile.guidance(),
            args.target_version
        ),
    );
    match args.profile {
        Profile::Rust => {
            if !args.target_version.is_empty() && args.target_version != "1.85" {
                return Err(err(
                    "Rust-каркас: minimum toolchain 1.85 / edition 2024. Для другого minimum используй AI blueprint.",
                ));
            }
            plan.target_version = "1.85".into();
            add(
                "Cargo.toml",
                format!(
                    "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2024\"\nrust-version = \"1.85\"\n\n[workspace]\n",
                    args.name
                ),
            );
            add("src/main.rs","fn greeting(name: &str) -> String {\n    format!(\"Hello, {name}!\")\n}\n\nfn main() {\n    let name = std::env::args().nth(1).unwrap_or_else(|| \"world\".into());\n    println!(\"{}\", greeting(&name));\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn greets_the_selected_name() {\n        assert_eq!(super::greeting(\"Lyra\"), \"Hello, Lyra!\");\n    }\n}\n".into());
            add(".gitignore", "/target/\n".into());
        }
        Profile::Python => {
            if !args.target_version.is_empty() && args.target_version != "3.11" {
                return Err(err(
                    "Python-каркас рассчитан на Python 3.11+; для другого minimum используй AI blueprint.",
                ));
            }
            plan.target_version = "3.11".into();
            add("main.py","\"\"\"Small standard-library CLI.\"\"\"\nimport argparse\n\n\ndef greeting(name: str) -> str:\n    return f\"Hello, {name}!\"\n\n\ndef main() -> None:\n    parser = argparse.ArgumentParser()\n    parser.add_argument(\"name\", nargs=\"?\", default=\"world\")\n    args = parser.parse_args()\n    print(greeting(args.name))\n\n\nif __name__ == \"__main__\":\n    main()\n".into());
            add("tests/test_main.py","import unittest\nfrom main import greeting\n\n\nclass GreetingTests(unittest.TestCase):\n    def test_selected_name(self):\n        self.assertEqual(greeting(\"Lyra\"), \"Hello, Lyra!\")\n".into());
            add(".gitignore", "__pycache__/\n.venv/\n".into());
        }
        Profile::TypeScript => {
            if !args.target_version.is_empty() && args.target_version != "node-22.18" {
                return Err(err(
                    "TypeScript-каркас: Node.js 22.18+ со встроенным удалением типов, без tsc. Для другого runtime используй AI blueprint.",
                ));
            }
            plan.target_version = "node-22.18".into();
            add(
                "package.json",
                format!(
                    r#"{{
  "name": "{}", "version": "0.1.0", "private": true, "type": "module",
  "engines": {{"node": ">=22.18.0"}},
  "scripts": {{"start": "node src/main.ts", "test": "node --test tests/greeting.test.ts"}}
}}
"#,
                    args.name
                ),
            );
            add("src/greeting.ts","export function greeting(name: string): string {\n  return `Hello, ${{name}}!`;\n}\n".replace("${{name}}","${name}"));
            add("src/main.ts","import { greeting } from './greeting.ts';\nconsole.log(greeting(process.argv[2] ?? 'world'));\n".into());
            add("tests/greeting.test.ts","import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport { greeting } from '../src/greeting.ts';\ntest('greets the selected name', () => { assert.equal(greeting('Lyra'), 'Hello, Lyra!'); });\n".into());
            add(".gitignore", "node_modules/\n".into());
            plan.assumptions.push("Node's type stripping executes TypeScript but does not type-check it. A pinned tsc/type-check setup requires a separate dependency choice.".into());
        }
        Profile::PaperJava | Profile::PaperKotlin | Profile::SpigotJava | Profile::SpigotKotlin => {
            profile::minecraft_version(&args.target_version)?;
            let paper = matches!(args.profile, Profile::PaperJava | Profile::PaperKotlin);
            let repo = if paper {
                "https://repo.papermc.io/repository/maven-public/"
            } else {
                "https://hub.spigotmc.org/nexus/content/repositories/snapshots/"
            };
            let group = if paper {
                "io.papermc.paper"
            } else {
                "org.spigotmc"
            };
            let artifact = if paper { "paper-api" } else { "spigot-api" };
            let kotlin = args.profile.kotlin();
            let kotlin_dependency = if kotlin {
                "\n    <dependency><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-stdlib</artifactId><version>2.4.21</version></dependency>"
            } else {
                ""
            };
            let kotlin_plugins = if kotlin {
                r#"
      <plugin>
        <groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-maven-plugin</artifactId><version>2.4.21</version>
        <configuration><jvmTarget>21</jvmTarget></configuration>
        <executions><execution><id>compile</id><phase>compile</phase><goals><goal>compile</goal></goals></execution></executions>
      </plugin>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId><artifactId>maven-shade-plugin</artifactId><version>3.6.2</version>
        <configuration><createDependencyReducedPom>false</createDependencyReducedPom></configuration>
        <executions><execution><phase>package</phase><goals><goal>shade</goal></goals></execution></executions>
      </plugin>"#
            } else {
                ""
            };
            let source = if kotlin {
                "<sourceDirectory>src/main/kotlin</sourceDirectory>"
            } else {
                ""
            };
            add(
                "pom.xml",
                format!(
                    r#"<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>local.generated</groupId><artifactId>{name}</artifactId><version>0.1.0</version>
  <properties><maven.compiler.release>21</maven.compiler.release><project.build.sourceEncoding>UTF-8</project.build.sourceEncoding></properties>
  <repositories><repository><id>server-api</id><url>{repo}</url></repository></repositories>
  <dependencies>
    <dependency><groupId>{group}</groupId><artifactId>{artifact}</artifactId><version>{version}-R0.1-SNAPSHOT</version><scope>provided</scope></dependency>{kotlin_dependency}
  </dependencies>
  <build>{source}
    <plugins>
      <plugin><groupId>org.apache.maven.plugins</groupId><artifactId>maven-compiler-plugin</artifactId><version>3.16.0</version></plugin>{kotlin_plugins}
    </plugins>
  </build>
</project>
"#,
                    name = args.name,
                    version = args.target_version
                ),
            );
            if kotlin {
                add("src/main/kotlin/local/generated/Main.kt","package local.generated\n\nimport org.bukkit.plugin.java.JavaPlugin\n\nclass Main : JavaPlugin() {\n    override fun onEnable() {\n        logger.info(\"Plugin enabled\")\n    }\n}\n".into());
            } else {
                add("src/main/java/local/generated/Main.java","package local.generated;\n\nimport org.bukkit.plugin.java.JavaPlugin;\n\npublic final class Main extends JavaPlugin {\n    @Override\n    public void onEnable() {\n        getLogger().info(\"Plugin enabled\");\n    }\n}\n".into());
            }
            add(
                "src/main/resources/plugin.yml",
                format!(
                    "name: '{}'\nversion: '0.1.0'\nmain: local.generated.Main\napi-version: '{}'\ndescription: 'Minimal starter, implement the requested feature separately'\n",
                    args.name, args.target_version
                ),
            );
            add(".gitignore", "/target/\n.idea/\n*.iml\n".into());
            if kotlin {
                add(
                    "src/main/resources/META-INF/licenses/kotlin-APACHE-2.0.txt",
                    include_str!("../../third_party/llama-cpp-rs/LICENSE-APACHE").into(),
                );
                add("src/main/resources/META-INF/licenses/KOTLIN-NOTICE.txt","Kotlin standard library 2.4.21\nCopyright JetBrains s.r.o. and Kotlin contributors.\nLicensed under Apache License 2.0.\nSource: https://github.com/JetBrains/kotlin\n".into());
            }
            plan.assumptions.push("JDK 21 + Maven required. API SNAPSHOT is not reproducibly pinned; record a resolved artifact/checksum before production. Server acceptance has not been performed.".into());
        }
        Profile::DayzEnforce => {
            if args.target_version.is_empty() {
                plan.questions.push(
                    "Укажи версию DayZ и подготовь соответствующий DayZ Tools/SDK для проверки."
                        .into(),
                );
            }
            let id = args.name.replace('-', "_");
            add(
                "config.cpp",
                format!(
                    r#"class CfgPatches
{{
    class {id}
    {{
        units[] = {{}};
        weapons[] = {{}};
        requiredVersion = 0.1;
        requiredAddons[] = {{"DZ_Data"}};
    }};
}};
class CfgMods
{{
    class {id}
    {{
        dir = "{id}";
        name = "{id}";
        type = "mod";
        dependencies[] = {{"Game"}};
        class defs
        {{
            class gameScriptModule
            {{
                value = "";
                files[] = {{"{id}/scripts/3_Game"}};
            }};
        }};
    }};
}};
"#
                ),
            );
            add(
                "mod.cpp",
                format!(
                    "name = \"{id}\";\nauthor = \"Project author\";\noverview = \"Minimal Enforce Script starter\";\n"
                ),
            );
            add(
                "scripts/3_Game/StarterMessage.c",
                format!(
                    "class {id}_StarterMessage\n{{\n    static string GetText()\n    {{\n        return \"Hello from Enforce Script\";\n    }}\n}}\n"
                ),
            );
            add(".gitignore", "*.pbo\n*.bisign\n*.biprivatekey\n".into());
            plan.assumptions.push("Enforce/DayZ syntax and config require the installed game SDK. This skeleton does not implement hooks, pack/sign the mod, or prove client/server compatibility. PBO prefix must match the config script path.".into());
        }
        _ => return Err(err("No starter for this profile")),
    }
    plan.validate()?;
    Ok(plan)
}
